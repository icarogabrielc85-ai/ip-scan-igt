def tr(key: str, default: str = None) -> str:
    """
    Returns translated text for key in the currently active language.
    Falls back gracefully to English, Portuguese, default, or key itself.
    """
    lang = get_current_language()
    entry = TRANSLATIONS.get(key)
    if entry:
        if lang in entry:
            return entry[lang]
        if "en" in entry:
            return entry["en"]
        if "pt_BR" in entry:
            return entry["pt_BR"]
    return default or key
